// Build-time only. Source: Natural Earth v5.1.2 (public domain).
// Usage: node scripts/generate-world-map.cjs <populated-places.geojson> <land.geojson>
const fs = require('node:fs');
const path = require('node:path');
const [placesPath, landPath, countriesPath] = process.argv.slice(2);
if (!placesPath || !landPath) throw new Error('Provide the two Natural Earth GeoJSON source files');
const places = JSON.parse(fs.readFileSync(placesPath, 'utf8'));
const land = JSON.parse(fs.readFileSync(landPath, 'utf8'));
const output = path.resolve(__dirname, '../src/features/cities');
const entries = places.features.map(({ properties: p, geometry: g }) => ({
  id: `ne-${p.NE_ID}`, name: p.NAME_ZH || p.NAME,
  aliases: [...new Set([p.NAME, p.NAME_EN, p.NAMEASCII].filter(Boolean))],
  region: p.ADM0NAME, latitude: g.coordinates[1], longitude: g.coordinates[0],
}));
fs.writeFileSync(path.join(output, 'world-place-data.ts'),
  '// Generated by scripts/generate-world-map.cjs from Natural Earth v5.1.2. Public domain.\n' +
  'export const worldPlaceData = ' + JSON.stringify(entries, null, 2) + ' as const;\n');
// Equirectangular projection covers the full geographic range, including both poles.
const project = ([lon, lat]) => [(lon + 180) * 10, (90 - lat) * 10];
const paths = land.features.flatMap(f => f.geometry.type === 'MultiPolygon' ? f.geometry.coordinates : [f.geometry.coordinates])
  .map(rings => rings.map(ring => ring.map((point, i) => {
    const [x, y] = project(point);
    return `${i ? 'L' : 'M'}${x.toFixed(2)},${y.toFixed(2)}`;
  }).join(' ') + ' Z').join(' '));
fs.writeFileSync(path.join(output, 'world-land-data.ts'),
  '// Generated by scripts/generate-world-map.cjs from Natural Earth v5.1.2. Public domain.\n' +
  'export const worldMapViewBox = "0 0 3600 1800";\n' +
  'export const worldLandPaths: readonly string[] = ' + JSON.stringify(paths) + ';\n');
if (countriesPath) {
  const countries = JSON.parse(fs.readFileSync(countriesPath, 'utf8'));
  // Build-time CLDR region labels keep map captions short; no Intl requirement on iPhone.
  const regionNames = new Intl.DisplayNames(['zh-CN'], { type: 'region' });
  const data = countries.features.map(({ properties: p, geometry: g }) => ({
    id: p.ADM0_A3, name: /^[A-Z]{2}$/.test(p.ISO_A2_EH) ? regionNames.of(p.ISO_A2_EH) : p.NAME_ZH || p.NAME,
    latitude: p.LABEL_Y, longitude: p.LABEL_X, labelRank: p.LABELRANK, minLabel: p.MIN_LABEL, importance: p.POP_EST,
    path: (g.type === 'MultiPolygon' ? g.coordinates : [g.coordinates]).map(rings => rings.map(ring => ring.map((point, i) => {
      const [x, y] = project(point);
      return `${i ? 'L' : 'M'}${x.toFixed(2)},${y.toFixed(2)}`;
    }).join(' ') + ' Z').join(' ')).join(' '),
  }));
  fs.writeFileSync(path.join(output, 'world-country-data.ts'),
    '// Generated from Natural Earth v5.1.2; public domain. Display boundaries only.\n' +
    'export const worldCountryData = ' + JSON.stringify(data, null, 2) + ' as const;\n');
}
console.log(JSON.stringify({ places: entries.length, landPaths: paths.length }));
