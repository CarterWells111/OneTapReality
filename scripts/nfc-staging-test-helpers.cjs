function formatInspectionSummary(manifest) {
  const lines = [`NFC staging batch ${manifest.batchId}`, `phase: ${manifest.phase}`];
  for (const name of SCENARIOS) {
    const scenario = manifest.scenarios?.[name];
    if (!scenario) continue;
    lines.push(`${name}: card=${scenario.cardId ?? "unknown"} gift=${scenario.giftId ?? "unclaimed"} state=${scenario.state ?? "unknown"}`);
  }
  return lines.join("\n");
}

function assertGuardState({ labExists, manifestExists, trackedText, environment = {} }) {
  if (labExists) throw new Error("Local NFC Lab route still exists");
  if (manifestExists) throw new Error("Active NFC staging manifest still exists");
  if (/\/gift\/[A-Za-z0-9_-]{32,}/u.test(trackedText)) throw new Error("A raw NFC gift token appears in tracked content");
  if (/[A-Za-z0-9._%+-]+\+nfc-(?:owner|viewer|editor)@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/iu.test(trackedText)) {
    throw new Error("A temporary NFC test email appears in tracked content");
  }
  const configuredOrigins = [environment.NFC_TEST_API_ORIGIN, environment.EXPO_PUBLIC_API_ORIGIN].filter(Boolean);
  if (configuredOrigins.some((origin) => origin !== STAGING_API_ORIGIN)) {
    throw new Error("A production or non-staging API configuration is active in the NFC test environment");
  }
  if (environment.NFC_TEST_GIFT_ORIGIN && environment.NFC_TEST_GIFT_ORIGIN !== STAGING_GIFT_ORIGIN) {
    throw new Error("A production or non-staging gift configuration is active in the NFC test environment");
  }
  if (environment.NFC_TEST_R2_BUCKET && environment.NFC_TEST_R2_BUCKET !== STAGING_R2_BUCKET) {
    throw new Error("A production or non-staging R2 configuration is active in the NFC test environment");
  }
}

async function seedScenarioMatrix({ client, manifest, persist, invalidToken = randomBytes(32).toString("base64url") }) {
  try {
    for (const name of SCENARIOS) {
      let scenario = manifest.scenarios[name];
      if (!scenario) {
        const note = `NFC-LAB:${manifest.batchId}:${name}`;
        const reservation = await client.reserveCard(note);
        scenario = manifest.scenarios[name] = {
          cardId: reservation.cardId,
          giftUrl: reservation.giftUrl,
          token: extractGiftToken(reservation.giftUrl),
          state: "reserved",
        };
        await persist(manifest);
        if (typeof client.getCard === "function") {
          const detail = await client.getCard(scenario.cardId);
          scenario.giftId = detail.card?.giftId ?? scenario.giftId;
          await persist(manifest);
        }
      }
      if (scenario.state === "reserved") {
        await client.activateCard(scenario.cardId);
        scenario.state = "active";
        if (typeof client.getCard === "function") {
          const detail = await client.getCard(scenario.cardId);
          scenario.giftId = detail.card?.giftId ?? scenario.giftId;
        }
        await persist(manifest);
      }
      if (name === "unclaimed") continue;
      let owned = null;
      if ((scenario.state === "active" || (name === "disabled" && scenario.state === "bound")) && typeof client.getCard === "function") {
        const detail = await client.getCard(scenario.cardId);
        scenario.giftId = detail.card?.giftId ?? scenario.giftId;
        if (detail.card?.giftStatus === "bound" && scenario.giftId && typeof client.getOwnedGift === "function") {
          owned = await client.getOwnedGift(scenario.giftId);
          scenario.state = "bound";
          await persist(manifest);
        } else if (detail.card?.giftStatus === "disabled") {
          scenario.state = "disabled";
          await persist(manifest);
        }
      }
      if (scenario.state === "active") {
        const claimed = await client.claimGift(scenario.token);
        scenario.giftId = claimed.id;
        scenario.state = "bound";
        await persist(manifest);
      }
      if ((name === "viewer" || name === "editor") && scenario.state === "bound") {
        owned = owned ?? (typeof client.getOwnedGift === "function" ? await client.getOwnedGift(scenario.giftId) : null);
        const memberExists = owned?.members?.some((member) => member.email === manifest.roleEmails[name] && member.role === name);
        if (!memberExists) await client.addMember(scenario.giftId, manifest.roleEmails[name], name);
        scenario.state = "member_added";
        await persist(manifest);
      }
      if ((name === "viewer" || name === "editor") && scenario.state === "member_added") {
        owned = typeof client.getOwnedGift === "function" ? await client.getOwnedGift(scenario.giftId) : null;
        if (owned?.album?.sourceMemoryId === `nfc-lab:${name}`) scenario.albumId = owned.album.id;
        else {
          const album = await client.publishAlbum(scenario.giftId, name);
          scenario.albumId = album.albumId;
        }
        scenario.state = "published";
        await persist(manifest);
      }
      if (name === "disabled" && scenario.state === "bound") {
        await client.disableGift(scenario.giftId);
        scenario.state = "disabled";
        await persist(manifest);
      }
    }
    manifest.invalidToken = manifest.invalidToken ?? invalidToken;
    manifest.phase = "ready";
    await persist(manifest);
    return manifest;
  } catch (error) {
    manifest.phase = "seed_failed";
    await persist(manifest);
    throw error;
  }
}

async function cleanupScenarioMatrix({ client, manifest, persist }) {
  manifest.phase = "cleaning";
  await persist(manifest);
  try {
    const failures = [];
    for (const [name, scenario] of Object.entries(manifest.scenarios ?? {})) {
      if (scenario.state === "revoked") continue;
      try {
        if (scenario.state === "reserved") {
          const detail = typeof client.getCard === "function" ? await client.getCard(scenario.cardId) : null;
          scenario.giftId = detail?.card?.giftId ?? scenario.giftId;
          if (detail?.card?.state === "active") scenario.state = "active";
          else if (detail?.card?.state === "retired") scenario.state = "revoked";
          else throw new Error(`Card ${name} is still initializing; retry after its staging reservation expires`);
        }
        if (scenario.state === "active") await client.retireCard(scenario.cardId);
        else if (scenario.state !== "disabled" && scenario.state !== "revoked" && scenario.giftId) await client.disableGift(scenario.giftId);
        scenario.state = "revoked";
        await persist(manifest);
      } catch (error) {
        failures.push(error);
      }
    }
    const maintenance = await client.runMaintenance();
    if ((maintenance.pending ?? 0) > 0 || (maintenance.failed ?? 0) > 0) {
      failures.push(new Error("Staging media maintenance did not finish cleanly"));
    }
    if (failures.length) {
      const reasons = failures.map((error) => error instanceof Error ? error.message : "unknown cleanup failure").join("; ");
      throw new AggregateError(failures, `One or more staging cleanup steps need a retry: ${reasons}`);
    }
    manifest.phase = "remote_cleaned";
    await persist(manifest);
    return manifest;
  } catch (error) {
    manifest.phase = "cleanup_failed";
    await persist(manifest);
    throw error;
  }
}

async function rollbackFailedSeed({ client, manifest, persist }) {
  try {
    await cleanupScenarioMatrix({ client, manifest, persist });
    manifest.phase = "seed_rolled_back";
    await persist(manifest);
    return manifest;
  } catch (error) {
    manifest.phase = "seed_rollback_failed";
    await persist(manifest);
    throw error;
  }
}

function createFixture(scenario) {
  const files = {
    viewer: "hangzhou-card-watercolor.png",
    editor: "shanghai-card-watercolor.png",
  };
  const fileName = files[scenario] ?? files.viewer;
  const path = join(process.cwd(), "assets", "cities", fileName);
  const bytes = readFileSync(path);
  return {
    bytes,
    byteSize: statSync(path).size,
    contentType: "image/png",
    title: scenario === "editor" ? "[NFC Demo] 上海协作相册" : "[NFC Demo] 杭州共享相册",
  };
}

function createStagingApiClient({
  apiOrigin,
  adminAccessToken,
  ownerAccessToken,
  maintenanceSecret,
  request = fetch,
  fixtureLoader = createFixture,
}) {
  if (apiOrigin !== STAGING_API_ORIGIN) throw new Error("The API client only supports the fixed staging origin");

  async function send(path, { method = "GET", token, body, headers = {}, expected = [200] } = {}) {
    const response = await request(`${apiOrigin}${path}`, {
      method,
      headers: {
        ...(body === undefined ? {} : { "Content-Type": "application/json" }),
        ...(token ? { Authorization: `Bearer ${token}` } : {}),
        ...headers,
      },
      ...(body === undefined ? {} : { body: JSON.stringify(body) }),
    });
    const text = await response.text();
    const payload = text ? JSON.parse(text) : null;
    if (!expected.includes(response.status)) {
      const code = payload?.error?.code ?? payload?.code ?? `http_${response.status}`;
      throw new Error(`Staging API ${path} failed: ${code}`);
    }
    return payload;
  }

  return {
    reserveCard: (note) => send("/api/admin/gift-cards", { method: "POST", token: adminAccessToken, body: { note }, expected: [201] }),
    getCard: (cardId) => send(`/api/admin/gift-cards/${encodeURIComponent(cardId)}`, { token: adminAccessToken, expected: [200] }),
    activateCard: (cardId) => send(`/api/admin/gift-cards/${encodeURIComponent(cardId)}/activate`, { method: "POST", token: adminAccessToken, expected: [200] }),
    retireCard: (cardId) => send(`/api/admin/gift-cards/${encodeURIComponent(cardId)}/retire`, { method: "POST", token: adminAccessToken, expected: [200] }),
    claimGift: (token) => send(`/api/gifts/${encodeURIComponent(token)}/claim`, { method: "POST", token: ownerAccessToken, expected: [201] }),
    addMember: (giftId, email, role) => send(`/api/my-gifts/${encodeURIComponent(giftId)}/members`, { method: "POST", token: ownerAccessToken, body: { email, role }, expected: [201] }),
    getOwnedGift: (giftId) => send(`/api/my-gifts/${encodeURIComponent(giftId)}/manage`, { token: ownerAccessToken, expected: [200] }),
    listInvited: (accessToken) => send("/api/gifts/invited", { token: accessToken, expected: [200] }).then((payload) => payload.items),
    disableGift: (giftId) => send(`/api/my-gifts/${encodeURIComponent(giftId)}/disable`, { method: "POST", token: ownerAccessToken, expected: [204] }),
    async publishAlbum(giftId, scenario) {
      const fixture = fixtureLoader(scenario);
      const page = {
        id: `nfc-lab-${scenario}`,
        position: 0,
        kind: "photo",
        headline: fixture.title,
        body: "NFC staging 测试批次的本地图片。",
      };
      const publication = await send(`/api/my-gifts/${encodeURIComponent(giftId)}/publish`, {
        method: "POST",
        token: ownerAccessToken,
        expected: [201],
        body: {
          baseVersion: 0,
          sourceMemoryId: `nfc-lab:${scenario}`,
          title: fixture.title,
          pages: [{ position: 0, page }],
          media: [{ position: 0, contentType: fixture.contentType, byteSize: fixture.byteSize }],
          cover: { contentType: fixture.contentType, byteSize: fixture.byteSize },
        },
      });
      const uploads = [
        ...publication.uploads.map((upload) => upload.uploadUrl),
        ...(publication.coverUpload ? [publication.coverUpload.uploadUrl] : []),
      ];
      for (const uploadUrl of uploads) {
        const upload = await request(uploadUrl, {
          method: "PUT",
          headers: { "Content-Type": fixture.contentType },
          body: fixture.bytes,
        });
        if (!upload.ok) throw new Error(`Staging R2 fixture upload failed with HTTP ${upload.status}`);
      }
      return send(`/api/my-gifts/${encodeURIComponent(giftId)}/publish`, {
        method: "PUT",
        token: ownerAccessToken,
        expected: [201],
        body: { publicationId: publication.publicationId },
      });
    },
    async runMaintenance() {
      if (!maintenanceSecret) throw new Error("GIFT_CARD_CLEANUP_SECRET is required for staging cleanup");
      const stats = await send("/api/internal/gift-maintenance", {
        method: "POST",
        headers: { "x-gift-maintenance-secret": maintenanceSecret },
        expected: [200],
      });
      return {
        pending: stats.skipped
          ? 1
          : Math.max(0, (stats.claimedCleanupJobs ?? 0) - (stats.completedCleanupJobs ?? 0) - (stats.failedCleanupJobs ?? 0) - (stats.deadLetteredCleanupJobs ?? 0)),
        failed: (stats.failedCleanupJobs ?? 0) + (stats.deadLetteredCleanupJobs ?? 0),
        stats,
      };
    },
  };
}

function installLocalLab({ manifest, labPath }) {
  mkdirSync(dirname(labPath), { recursive: true });
  writeFileSync(labPath, buildLocalLabSource(manifest), { encoding: "utf8", mode: 0o600 });
}

function removeLocalArtifacts({ labPath, manifestPath }) {
  rmSync(labPath, { force: true });
  rmSync(manifestPath, { force: true });
}

async function verifyAllowlistRollback({ apiOrigin, emails, request = fetch }) {
  if (apiOrigin !== STAGING_API_ORIGIN) throw new Error("Allowlist rollback can only be checked against staging");
  for (const email of emails) {
    const response = await request(`${apiOrigin}/api/auth/request`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ email }),
    });
    let payload = null;
    try { payload = await response.json(); } catch { /* invalid responses fail below */ }
    if (response.status !== 403 || payload?.error?.code !== "beta_invite_required") {
      throw new Error("Temporary NFC test email is still present in the staging allowlist");
    }
  }
}

