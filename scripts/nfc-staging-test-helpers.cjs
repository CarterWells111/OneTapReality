const { mkdirSync, readFileSync, renameSync, rmSync, statSync, writeFileSync } = require("node:fs");
const { dirname, join } = require("node:path");
const { randomBytes } = require("node:crypto");

const STAGING_API_ORIGIN = "https://api-staging.onetapreality.com";
const STAGING_GIFT_ORIGIN = "https://staging.onetapreality.com";
const STAGING_R2_BUCKET = "onetapreality-staging";
const CONFIRMATION = "CREATE-NFC-STAGING-LAB";
const SCENARIOS = ["unclaimed", "owner", "viewer", "editor", "disabled"];

function assertStagingConfiguration(input) {
  if (input.apiOrigin !== STAGING_API_ORIGIN) throw new Error("NFC lab API origin must be the fixed staging API origin");
  if (input.giftOrigin !== STAGING_GIFT_ORIGIN) throw new Error("NFC lab gift origin must be the fixed staging gift origin");
  if (input.r2Bucket !== STAGING_R2_BUCKET) throw new Error("NFC lab R2 bucket must be the fixed staging bucket");
  if (input.confirmation !== CONFIRMATION) throw new Error(`NFC staging confirmation must equal ${CONFIRMATION}`);
}

function deriveRoleEmails(baseEmail) {
  const normalized = String(baseEmail ?? "").trim().toLowerCase();
  const match = normalized.match(/^([^\s@]+)@([^\s@]+\.[^\s@]+)$/u);
  if (!match) throw new Error("A valid base email is required");
  const local = match[1].split("+", 1)[0];
  const domain = match[2];
  return {
    owner: `${local}+nfc-owner@${domain}`,
    viewer: `${local}+nfc-viewer@${domain}`,
    editor: `${local}+nfc-editor@${domain}`,
  };
}

function extractGiftToken(giftUrl) {
  let url;
  try {
    url = new URL(giftUrl);
  } catch {
    throw new Error("The gift URL is invalid");
  }
  if (url.origin !== STAGING_GIFT_ORIGIN) throw new Error("The gift URL must use the staging gift origin");
  const match = url.pathname.match(/^\/gift\/([A-Za-z0-9_-]+)$/u);
  if (!match || url.search || url.hash) throw new Error("The staging gift URL must contain exactly one gift token");
  return match[1];
}

function defaultBatchId() {
  const stamp = new Date().toISOString().replace(/[-:]/gu, "").replace(/\.\d{3}Z$/u, "Z");
  return `${stamp}-${randomBytes(3).toString("hex")}`;
}

function createInitialManifest(baseEmail, batchId = defaultBatchId()) {
  return {
    version: 1,
    batchId,
    phase: "seeding",
    createdAt: new Date().toISOString(),
    apiOrigin: STAGING_API_ORIGIN,
    giftOrigin: STAGING_GIFT_ORIGIN,
    r2Bucket: STAGING_R2_BUCKET,
    roleEmails: deriveRoleEmails(baseEmail),
    scenarios: {},
  };
}

function writeManifestAtomic(path, manifest) {
  mkdirSync(dirname(path), { recursive: true });
  const temporary = `${path}.tmp`;
  writeFileSync(temporary, `${JSON.stringify(manifest, null, 2)}\n`, { encoding: "utf8", mode: 0o600 });
  renameSync(temporary, path);
}

