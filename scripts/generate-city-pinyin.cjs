const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const { customPinyin, pinyin } = require('pinyin-pro');

// Development only. Loading the pure registry also supports its future TS data imports.
require.extensions['.ts'] = (module, filename) => {
  const compiled = ts.transpileModule(fs.readFileSync(filename, 'utf8'), {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
  });
  module._compile(compiled.outputText, filename);
};
customPinyin({ 长春: 'cháng chūn', 长沙: 'cháng shā', 重庆: 'chóng qìng', 厦门: 'xià mén' });

function keyForName(name) {
  return pinyin(name, { toneType: 'none', type: 'array', nonZh: 'consecutive', v: true })
    .join('').normalize('NFKD').replace(/[\u0300-\u036f]/g, '').toLowerCase().replace(/[^a-z0-9]/g, '');
}
function generate(entries) {
  const keys = {};
  for (const { id, name } of [...entries].sort((a,b) => a.id < b.id ? -1 : a.id > b.id ? 1 : 0)) {
    if (keys[id]) throw new Error(`Duplicate city ID: ${id}`);
    const key = keyForName(name);
    keys[id] = { name, key, initial: /^[a-z]/.test(key) ? key[0].toUpperCase() : '#' };
  }
  return keys;
}
module.exports = { generate, keyForName };
if (require.main === module) {
  const { cityRegistry } = require('../src/types/city.ts');
  const output = '// Generated by scripts/generate-city-pinyin.cjs. Do not edit by hand.\n'
    + 'export const cityPinyinKeys: Readonly<Record<string, { name: string; key: string; initial: string }>> = '
    + JSON.stringify(generate(cityRegistry), null, 2) + ';\n';
  const target = path.join(__dirname, '../src/features/cities/city-pinyin.generated.ts');
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target,'utf8').replace(/\r\n/g,'\n') !== output) {
      console.error('City pinyin data is stale. Run npm run cities:generate.'); process.exitCode = 1;
    }
  } else { fs.writeFileSync(target, output); }
}
